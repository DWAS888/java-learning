package com.javaLearning.interal;

public class interal_demo1{
    //打印：霸王龙 11.5 8 公
    public static void main(String[] args) {
        System.out.println("霸王龙");    //字符串
        System.out.println(11.5);       //浮点数
        System.out.println(8);          //整数
        System.out.println('公');       //字符
    }
}
