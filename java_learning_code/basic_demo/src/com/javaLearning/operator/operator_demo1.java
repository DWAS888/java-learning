package com.javaLearning.operator;

public class operator_demo1 {
    static void main(String[] args) {


        //整数计算
        int num1 = 36;
        int num2 = 17;

        System.out.println(num1 + num2);
        System.out.println(num1 - num2);
        System.out.println(num1 * num2);
        System.out.println(num1 / num2);
        System.out.println(num1 % num2);

        //浮点数计算
        double num3 = 36.0;
        double num4 = 17.0;
        System.out.println(num3 + num4);
        System.out.println(num3 - num4);
        System.out.println(num3 * num4);
        System.out.println(num3 / num4);
        System.out.println(num3 % num4);


    }
}
